#!/usr/bin/env node
/**
 * Hero dotted arcs: Figma exports → the assets the page uses.
 *
 * Source: design-system/reference/figma-exports/hero-arc-{left,right}.src.svg
 * (Figma 596:2557 / 596:2559 — one tapered brush stroke of ~1,200 stamps
 * drawn once round the ellipse: large stamps at the start, shrinking to
 * nothing at the end, which finishes right beside the start).
 *
 * Two repairs, nothing else changes (stamps, sizes, colours, group opacity):
 *  1. Bounds. The export's viewBox is the ellipse's bounding box, but the
 *     large stamps at the stroke's start overhang it by up to ~45 units, and an
 *     <img> clips everything outside its viewBox — a straight cut through the
 *     thickest dots. The viewBox grows by MARGIN on every side (HeroFlight.css
 *     offsets the image by the same amount, so the artwork does not move).
 *  2. The join. The thick start began at full strength right next to the
 *     vanishing end. The first HEAD stamps now fade in along a smootherstep
 *     curve (~20° of arc), so the narrow tail runs into a head that swells in
 *     gradually — the taper is kept, the abrupt edge is gone.
 *
 *   node scripts/derive-hero-arcs.mjs          write src/assets/figma/hero-arc-*.svg
 *   node scripts/derive-hero-arcs.mjs --check  fail if they are out of date (npm run check)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const MARGIN = 60;
const HEAD = 14;
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const smootherstep = (t) => t * t * t * (t * (t * 6 - 15) + 10);

let stale = 0;
for (const side of ['left', 'right']) {
  const src = resolve(root, `design-system/reference/figma-exports/hero-arc-${side}.src.svg`);
  const dst = resolve(root, `src/assets/figma/hero-arc-${side}.svg`);
  let svg = readFileSync(src, 'utf8');

  const [, w, h] = /width="([\d.]+)" height="([\d.]+)" viewBox="0 0 [\d.]+ [\d.]+"/.exec(svg);
  const W = parseFloat(w);
  const H = parseFloat(h);
  const r = (v) => +v.toFixed(3);
  svg = svg.replace(
    /width="[\d.]+" height="[\d.]+" viewBox="0 0 [\d.]+ [\d.]+"/,
    `width="${r(W + 2 * MARGIN)}" height="${r(H + 2 * MARGIN)}" viewBox="${-MARGIN} ${-MARGIN} ${r(W + 2 * MARGIN)} ${r(H + 2 * MARGIN)}"`,
  );

  let i = 0;
  svg = svg.replace(/<use\b([^>]*?)\/>/g, (m, attrs) => {
    const k = i++;
    if (k >= HEAD) return m;
    const o = smootherstep((k + 1) / (HEAD + 1));
    return `<use${attrs} opacity="${o.toFixed(3)}"/>`;
  });

  const body = `<!-- GENERATED by scripts/derive-hero-arcs.mjs from design-system/reference/figma-exports/hero-arc-${side}.src.svg — do not edit -->
${svg}`;
  if (check) {
    if (!existsSync(dst) || readFileSync(dst, 'utf8') !== body) stale += 1;
  } else {
    writeFileSync(dst, body);
    console.log(`✓ wrote ./src/assets/figma/hero-arc-${side}.svg (viewBox +${MARGIN}, ${HEAD} head stamps faded in)`);
  }
}
if (check) {
  if (stale) {
    console.error('✗ hero arc assets are out of date — run `node scripts/derive-hero-arcs.mjs`.');
    process.exit(1);
  }
  console.log('✓ hero arc assets match their Figma sources');
}
